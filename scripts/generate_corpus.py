def make_id(cat, idx):
    return f"kb-{cat[:3]}-{idx:03d}"

docs = []
doc_index = {}
for cat, spec in CLUSTERS.items():
    products = spec["products"]
    for i, (title, body, diff, updated, authority) in enumerate(spec["docs"], start=1):
        doc_id = make_id(cat, i)
        product = products[(i - 1) % len(products)]
        doc = {
            "id": doc_id,
            "title": title,
            "text": body,
            "category": cat,
            "product": product,
            "metadata": {
                "difficulty": diff,
                "last_updated": updated,
                "source_authority": authority,
            },
        }
        docs.append(doc)
        doc_index[(cat, i)] = doc_id

